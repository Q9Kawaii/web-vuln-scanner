"""
report.py - Prints a summary and saves findings as JSON and HTML.

The HTML report is made with a Jinja2 template. Autoescaping is turned ON,
which matters here: our findings contain XSS payloads, and without escaping
the report itself would become vulnerable when opened in a browser.
"""

import json
from datetime import datetime

from colorama import Fore, Style
from jinja2 import Environment

SEVERITY_ORDER = {"High": 0, "Medium": 1, "Low": 2}
SEVERITY_COLOR = {"High": Fore.RED, "Medium": Fore.YELLOW, "Low": Fore.BLUE}

HTML_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>VulnScan Report</title>
<style>
  body { font-family: Arial, sans-serif; margin: 24px; background: #f5f6f8; color: #222; }
  h1 { margin-bottom: 4px; }
  .meta { color: #555; margin-bottom: 16px; }
  .cards { display: flex; gap: 12px; margin-bottom: 20px; flex-wrap: wrap; }
  .card { background: #fff; padding: 12px 20px; border-radius: 6px; box-shadow: 0 1px 3px #0002; }
  .card b { font-size: 22px; display: block; }
  table { width: 100%; border-collapse: collapse; background: #fff; box-shadow: 0 1px 3px #0002; }
  th, td { padding: 8px 10px; border-bottom: 1px solid #e3e3e3; text-align: left; vertical-align: top; font-size: 14px; }
  th { background: #2d3e50; color: #fff; }
  code { background: #eef; padding: 1px 4px; word-break: break-all; }
  .sev { font-weight: bold; padding: 2px 8px; border-radius: 4px; color: #fff; }
  .High { background: #c0392b; } .Medium { background: #d68910; } .Low { background: #2874a6; }
  .note { margin-top: 20px; font-size: 13px; color: #666; }
</style>
</head>
<body>
<h1>VulnScan Report</h1>
<div class="meta">Target: <b>{{ target }}</b> &middot; Scanned: {{ date }} &middot;
  Pages crawled: {{ pages }} &middot; Requests sent: {{ requests }} &middot; Checks: {{ checks }}</div>

<div class="cards">
  <div class="card"><b>{{ findings|length }}</b>Total findings</div>
  {% for sev in ["High", "Medium", "Low"] %}
  <div class="card"><b>{{ counts[sev] }}</b>{{ sev }}</div>
  {% endfor %}
</div>

{% if findings %}
<table>
  <tr><th>#</th><th>Severity</th><th>Vulnerability</th><th>URL</th><th>Parameter</th>
      <th>Payload</th><th>Evidence</th><th>How to fix</th></tr>
  {% for f in findings %}
  <tr>
    <td>{{ loop.index }}</td>
    <td><span class="sev {{ f.severity }}">{{ f.severity }}</span></td>
    <td>{{ f.vulnerability }}</td>
    <td>{{ f.method }} <code>{{ f.url }}</code></td>
    <td><code>{{ f.parameter }}</code></td>
    <td><code>{{ f.payload }}</code></td>
    <td>{{ f.evidence }}</td>
    <td>{{ f.fix }}</td>
  </tr>
  {% endfor %}
</table>
{% else %}
<p>No vulnerabilities were detected. This does not prove the site is secure.</p>
{% endif %}

<p class="note">Generated by VulnScan, an educational black-box scanner. Results may contain
false positives and must be verified manually. Only scan systems you own or are authorised to test.</p>
</body>
</html>
"""


def sort_findings(findings):
    return sorted(findings, key=lambda f: SEVERITY_ORDER.get(f["severity"], 9))


def print_summary(findings):
    """Print a short coloured summary to the terminal."""
    print(f"\n{Style.BRIGHT}=== Scan summary: {len(findings)} finding(s) ==={Style.RESET_ALL}")
    for f in sort_findings(findings):
        color = SEVERITY_COLOR.get(f["severity"], "")
        print(f"{color}[{f['severity']}]{Style.RESET_ALL} {f['vulnerability']}")
        print(f"    URL:       {f['method']} {f['url']}")
        print(f"    Parameter: {f['parameter']}")
        print(f"    Payload:   {f['payload']}")


def save_reports(findings, base_name, scan_info):
    """Write <base_name>.json and <base_name>.html. Returns both file paths."""
    findings = sort_findings(findings)
    info = dict(scan_info, date=datetime.now().strftime("%Y-%m-%d %H:%M:%S"))

    json_path = base_name + ".json"
    with open(json_path, "w", encoding="utf-8") as fh:
        json.dump({"scan": info, "findings": findings}, fh, indent=2)

    counts = {sev: sum(1 for f in findings if f["severity"] == sev) for sev in SEVERITY_ORDER}
    template = Environment(autoescape=True).from_string(HTML_TEMPLATE)
    html_path = base_name + ".html"
    with open(html_path, "w", encoding="utf-8") as fh:
        fh.write(template.render(findings=findings, counts=counts, **info))

    return json_path, html_path
